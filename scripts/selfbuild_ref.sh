#!/bin/bash
#
# racccoon builds its own kernel (docs/manual.md §9.8): stages what the
# on-device build needs and makes the host reference it must match.
#
#   build/selfbuild/racccoon/   -> /src/racccoon on the QEMU images:
#       project.json, src/, boards/, embed/*.bin.o (the user programs the
#       QEMU test kernel embeds), selfbuild.rc (the build, as a script)
#   build/selfbuild/ref/        -> /src/racccoon-ref:
#       kernel.elf   the same build run on the host
#       c3ctest.o    test/c3-src/c3ctest.c3, compile-only -g0
#
# The host side uses the SAME c3c source (C3C_SRC, see
# lib/racccoon-libc/build_c3c.sh) built natively against the host's LLVM —
# the same LLVM version racccoon's LLVM is built from — plus the host's
# llc / ld.lld of that version, and the stdlib from C3C_SRC/lib (which is
# also what's seeded as /lib/c3). So the only thing that differs from the
# on-device build is the machine running it. -g0: DWARF would carry the
# (different) absolute source paths; without it the IR has none.
#
# Needs build/user/*.bin.o and build/user_qemu_shell/shell.bin.o (the QEMU
# kernel step of scripts/build.sh). Skipped without C3C_SRC.

set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
. scripts/lib_kernel.sh   # KERNEL_SERVERS

C3C_SRC="${C3C_SRC:-$HOME/Workspace/c3c-llvm}"
if [ ! -e "$C3C_SRC/src/compiler/compiler.c" ]; then
  echo "scripts/selfbuild_ref.sh: no c3c at C3C_SRC=$C3C_SRC — self-build fixtures skipped." >&2
  exit 0
fi

# --- the host c3c (same source, host LLVM, shared libs) -----------------
HOSTC3C="build/c3c-host"
if [ ! -e "$HOSTC3C/build.ninja" ]; then
  echo "==> selfbuild: configuring the host c3c ($C3C_SRC)"
  cmake -G Ninja -S "$C3C_SRC" -B "$HOSTC3C" -DCMAKE_BUILD_TYPE=Release -DC3_LINK_DYNAMIC=ON \
    > "$HOSTC3C.configure.log" 2>&1 || { tail -20 "$HOSTC3C.configure.log"; exit 1; }
fi
ninja -C "$HOSTC3C" c3c > "$HOSTC3C.build.log" 2>&1 || { grep -E "error" "$HOSTC3C.build.log" | head; exit 1; }
C3C="$ROOT/$HOSTC3C/c3c"
STDLIB="$C3C_SRC/lib/std"

# --- the staged tree ---------------------------------------------------
OUT="build/selfbuild"
rm -rf "$OUT"
mkdir -p "$OUT/racccoon/embed" "$OUT/racccoon/lib" "$OUT/ref"   # lib: project.json's dependency path (no C3 libs are used)
cp -r project.json src boards "$OUT/racccoon/"
# The test shell as the QEMU kernel embeds it (_binary_shell_bin_*,
# lib_kernel.sh's kernel_test_shell_obj), and the servers. Linked as the
# glob embed/*.bin.o — sorted by byte order on both sides, so host and
# racccoon link them in the same order.
cp build/user_qemu_shell/shell.bin.o "$OUT/racccoon/embed/"
for s in $KERNEL_SERVERS; do
  cp "build/user/$s.bin.o" "$OUT/racccoon/embed/"
done

C3C_ARGS="build racccoon --no-entry --safe=no --riscv-cpu=rvimac --riscv-abi=double --emit-llvm -g0"
LLC_ARGS="-mtriple=riscv64-unknown-elf -mattr=+m,+a,+c,+f,+d -code-model=medium -relocation-model=static -filetype=obj"
LD_ARGS="build/llvm/elf-riscv64/*.o embed/*.bin.o -T src/kernel.ld -o build/kernel.elf"


# --- the host reference: the same steps, in a copy ----------------------
HOST="$OUT/host"
cp -r "$OUT/racccoon" "$HOST"
(
  cd "$HOST"
  export LC_ALL=C   # byte-order globs, like racccoon's shell
  "$C3C" $C3C_ARGS --stdlib "$STDLIB" > build.log 2>&1 || { cat build.log; exit 1; }
  for f in build/llvm/elf-riscv64/*.ll; do
    llc $LLC_ARGS -o "$f.o" "$f"
  done
  ld.lld $LD_ARGS
)
cp "$HOST/build/kernel.elf" "$OUT/ref/kernel.elf"

# The device script, written after the host build so it can name the IR
# modules c3c emits: their llc runs go 4 at a time (`cmd &` ... `wait`),
# one per hart on the Orange Pi (SMP).
{
  cat <<EOF
#!/bin/rc
# racccoon building its own QEMU test kernel — generated by
# scripts/selfbuild_ref.sh, which runs the same three steps on the host
# for /src/racccoon-ref/kernel.elf (selfbuildtest compares the two).
# lib_kernel.sh's kernel_compile + kernel_link, minus debug info; the
# llc jobs run 4 at a time.
cd /src/racccoon
c3c $C3C_ARGS
EOF
  n=0
  for f in $(cd "$HOST" && LC_ALL=C ls build/llvm/elf-riscv64/*.ll); do
    echo "llc $LLC_ARGS -o $f.o $f &"
    n=$((n + 1))
    if [ $((n % 4)) -eq 0 ]; then echo "wait"; fi
  done
  if [ $((n % 4)) -ne 0 ]; then echo "wait"; fi
  echo "ld.lld $LD_ARGS"
} > "$OUT/racccoon/selfbuild.rc"
"$C3C" compile-only --target elf-riscv64 --use-stdlib=no --no-entry --single-module=yes -g0 \
  test/c3-src/c3ctest.c3 -o "$OUT/ref/c3ctest.o" > /dev/null
echo "==> Done: $OUT/ref/kernel.elf ($(stat -c %s "$OUT/ref/kernel.elf") bytes), $OUT/ref/c3ctest.o"
