#!/bin/bash
#
# c3c compiling itself on racccoon (c3cselftest, docs/manual.md §9.8):
# turns the cross build of c3c (lib/racccoon-libc/build_c3c.sh — its
# compile_commands.json and its link command) into the same build done
# by /bin/clang + /bin/ld.lld on racccoon, and stages everything it reads:
#
#   build/c3cself/c3c/   -> /src/c3c       c3c's sources + the build dir's
#                                         generated headers, c3cbuild.rc,
#                                         rsp/*.rsp (flags: a compile line
#                                         is ~1 KB, over the shell's limit)
#   build/c3cself/sys/   -> /src/sys       LLVM + lld headers (the libc and
#                                         libc++ ones are seed_toolchain.sh's),
#                                         lib/: every archive c3c links
#   build/c3cself/ref/   -> /src/c3c-ref   the cross-built c3c ELF
#
# The cross build already compiles with -ffile-prefix-map to these device
# paths, so its ELF is what racccoon's rebuild must reproduce byte for
# byte. LLVM's own libraries are not rebuilt here (that's days under
# QEMU): they're linked from the cross build, exactly as c3c's own build
# links them. Ext2-only (scripts/build.sh): ~330 MB.

set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

C3C_SRC="${C3C_SRC:-$HOME/Workspace/c3c-llvm}"
LLVM_SRC="${LLVM_SRC:-$HOME/Workspace/llvm-project}"
B="build/c3c-racccoon"
[ -e "$B/compile_commands.json" ] && [ -e "$B/c3c" ] || {
  echo "scripts/c3cbuild_ref.sh: no cross-built c3c with compile_commands.json — c3c self-build skipped." >&2
  exit 0
}

OUT="build/c3cself"
rm -rf "$OUT"
mkdir -p "$OUT/c3c/rsp" "$OUT/sys/lib" "$OUT/ref"
cp "$B/c3c" "$OUT/ref/c3c"

RES="$(clang -print-resource-dir)/include"
LIBGCC="$(riscv64-unknown-elf-gcc -print-libgcc-file-name)"

python3 - "$ROOT" "$C3C_SRC" "$LLVM_SRC" "$RES" "$LIBGCC" <<'PY'
import json, os, shlex, subprocess, sys, shutil
root, c3c_src, llvm_src, res, libgcc = sys.argv[1:]
B = os.path.join(root, "build/c3c-racccoon")
OUT = os.path.join(root, "build/c3cself")

# host root -> device path (most specific first)
maps = [
    (B, "/src/c3c/build"),
    (c3c_src, "/src/c3c"),
    (os.path.join(root, "lib/racccoon-libc/include"), "/src/sys/libc/include"),
    (os.path.join(root, "build/cxx/install/include/c++/v1"), "/src/sys/libcxx/include"),
    (res, "/lib/clang/23/include"),
    (os.path.join(root, "build/llvm-racccoon/tools/lld/include"), "/src/sys/lld-build/include"),
    (os.path.join(root, "build/llvm-racccoon/include"), "/src/sys/llvm-build/include"),
    (os.path.join(llvm_src, "llvm/include"), "/src/sys/llvm/include"),
    (os.path.join(llvm_src, "lld/include"), "/src/sys/lld/include"),
]
def dev(p):
    for h, d in maps:
        if p == h or p.startswith(h + "/"):
            return d + p[len(h):]
    return p

cmds = json.load(open(os.path.join(B, "compile_commands.json")))
compiles = []
lines = ["#!/bin/rc",
         "# c3c rebuilding itself on racccoon — generated by scripts/c3cbuild_ref.sh",
         "# from the cross build's compile_commands.json + link command.",
         "cd /src/c3c/build"]
rsp_of = {}
objdirs = set()
for e in cmds:
    argv = shlex.split(e["command"]) if "command" in e else e["arguments"]
    cxx = argv[0].endswith("++")
    flags, src, obj = [], None, None
    i = 1
    while i < len(argv):
        a = argv[i]
        if a == "-o": obj = argv[i + 1]; i += 2; continue
        if a == "-c": src = argv[i + 1]; i += 2; continue
        if a in ("-MD",): i += 1; continue
        if a in ("-MT", "-MF"): i += 2; continue
        if a.startswith("-ffile-prefix-map="): i += 1; continue
        flags.append(dev(a) if a.startswith("/") else
                     (a[:2] + dev(a[2:]) if a[:2] in ("-I",) and a[2:].startswith("/") else a))
        i += 1
    # "-isystem <path>" pairs: the path is its own argv element (handled above)
    key = ("c++" if cxx else "c") + "\0" + "\0".join(flags)
    if key not in rsp_of:
        n = "rsp/%d.rsp" % len(rsp_of)
        rsp_of[key] = n
        with open(os.path.join(OUT, "c3c", n), "w") as f:
            f.write(" ".join(shlex.quote(x) for x in flags) + "\n")
    drv = "clang --driver-mode=g++" if cxx else "clang"
    objdirs.add(os.path.dirname(obj))
    compiles.append("%s @/src/c3c/%s -c %s -o %s" % (drv, rsp_of[key], dev(src), obj))

# The compiles run JOBS at a time — `cmd &` ... then `wait` (rc's job
# control): racccoon schedules them on every hart (SMP, the Orange Pi's
# four U74s). The archives and the link need them all, after a last wait.
JOBS = 4
for k in range(0, len(compiles), JOBS):
    for c in compiles[k:k + JOBS]:
        lines.append(c + " &")
    lines.append("wait")

# The static libraries (ninja: `llvm-ar qc lib.a objs && llvm-ranlib
# lib.a`), then the link, as ninja runs them. ninja's two `cmake -P`
# steps generate headers (git_hash.h, docs_template.h) — shipped already
# generated with the build dir's other headers.
allcmds = subprocess.check_output(["ninja", "-C", B, "-t", "commands", "c3c"], text=True).strip().splitlines()
for c in allcmds:
    if "llvm-ar qc" in c:
        parts = [p.strip() for p in c.split("&&")]
        ar = next(p for p in parts if p.startswith("/usr/bin/llvm-ar") or " llvm-ar qc" in p or p.startswith("llvm-ar"))
        aargv = shlex.split(ar)
        lines.append("llvm-ar " + " ".join(aargv[1:]))
        lines.append("llvm-ar s " + aargv[2])
link = allcmds[-1]
link = link.split("&&")[1] if "&&" in link else link
largv = shlex.split(link.strip().rstrip(":").strip())
assert largv[0].endswith("ld.lld"), largv[:3]
out_args = []
prev = ""
for a in largv[1:]:
    if prev == "-L":                           # the libc dir (-lm -lpthread -lrt -ldl): its archives move too
        for l in ("libm.a", "libpthread.a", "librt.a", "libdl.a"):
            shutil.copy(os.path.join(a, l), os.path.join(OUT, "sys/lib", l))
        out_args.append("/src/sys/lib"); prev = a; continue
    prev = a
    if a.startswith("-L/"):                    # the LLVM lib dir → /src/sys/lib; the host's /usr/lib → gone
        if a in ("-L/usr/lib", "-L/usr/lib64"): continue
        out_args.append("-L/src/sys/lib"); continue
    if a.endswith(".a") or (a.endswith(".o") and a.startswith("/")) or a.endswith(".ld"):
        if a.startswith("/"):
            base = os.path.basename(a)
            dst = os.path.join(OUT, "sys/lib", base)
            if not os.path.exists(dst): shutil.copy(a, dst)
            a = "/src/sys/lib/" + base
    out_args.append(a)
with open(os.path.join(OUT, "c3c/rsp/link.rsp"), "w") as f:
    f.write(" ".join(shlex.quote(x) for x in out_args) + "\n")
lines.append("ld.lld @/src/c3c/rsp/link.rsp")
with open(os.path.join(OUT, "c3c/c3cbuild.rc"), "w") as f:
    f.write("\n".join(lines) + "\n")
with open(os.path.join(OUT, "objdirs"), "w") as f:
    f.write("\n".join(sorted(objdirs)) + "\n")
print("%d compiles, %d flag sets, %d link inputs" % (len(cmds), len(rsp_of), len(out_args)))
PY

# the source trees the compiles read
mkdir -p "$OUT/c3c/build"
cp -r "$C3C_SRC/src" "$C3C_SRC/wrapper" "$C3C_SRC/dependencies" "$OUT/c3c/"
( cd "$B" && find . -name "*.h" -o -name "*.inc" -o -name "*.def" ) | while read -r f; do
  mkdir -p "$OUT/c3c/build/$(dirname "$f")"; cp "$B/$f" "$OUT/c3c/build/$f"
done
while read -r d; do [ -n "$d" ] && mkdir -p "$OUT/c3c/build/$d"; done < "$OUT/objdirs"
rm "$OUT/objdirs"
mkdir -p "$OUT/sys/llvm" "$OUT/sys/llvm-build" "$OUT/sys/lld" "$OUT/sys/lld-build"
cp -r "$LLVM_SRC/llvm/include" "$OUT/sys/llvm/include"
cp -r build/llvm-racccoon/include "$OUT/sys/llvm-build/include"
cp -r "$LLVM_SRC/lld/include" "$OUT/sys/lld/include"
cp -r build/llvm-racccoon/tools/lld/include "$OUT/sys/lld-build/include"
echo "==> Done: $OUT ($(du -sh "$OUT" | cut -f1)), $(grep -c '^clang' "$OUT/c3c/c3cbuild.rc") compiles"
